/**
 * PayPath - AI Diagnostic Engine
 * Analyzes sanitized payment traces and deterministic invariant violations
 * to produce root-cause hypotheses, verified code diffs, and proposed regression tests.
 * 
 * Supports Google Gemini API (via @google/genai or REST) with a transparent
 * fallback to an offline deterministic expert system when API keys are unconfigured.
 */

import { GoogleGenAI } from '@google/genai';
import { TestRunRecord, AIDiagnosisResult, AIConfigStatus } from './types';
import { sanitizePayload } from './sanitization';

export function getAIConfigStatus(): AIConfigStatus {
  const apiKey = process.env.GEMINI_API_KEY || process.env.AI_API_KEY;
  const hasApiKey = Boolean(apiKey && apiKey.trim().length > 0);

  return {
    provider: hasApiKey ? 'gemini' : 'none',
    hasApiKey,
    model: 'gemini-2.5-flash',
    available: hasApiKey,
  };
}

