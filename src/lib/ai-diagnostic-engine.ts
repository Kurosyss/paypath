/**
 * Executes AI diagnosis using Gemini API or Deterministic Engine
 */
export async function diagnoseRun(run: TestRunRecord): Promise<AIDiagnosisResult> {
  const apiKey = process.env.GEMINI_API_KEY || process.env.AI_API_KEY;

  if (!apiKey || apiKey.trim().length === 0) {
    // Return transparently labeled deterministic expert diagnosis
    return generateDeterministicExpertDiagnosis(run);
  }

  try {
    const ai = new GoogleGenAI({ apiKey });

    // Prepare fully sanitized trace context
    const sanitizedTraces = sanitizePayload(run.traces);
    const sanitizedInvariants = sanitizePayload(run.invariants);

    const prompt = `You are PayPath's Senior PayPal Reliability & Diagnostic AI Engine.
Analyze the following test run execution traces and invariant violations from our PayPal Payment Reliability Lab:

Scenario: ${run.scenarioTitle} (${run.scenarioId})
Mode: ${run.mode}
Status: ${run.status}
Initial State: ${run.initialState}
Final State: ${run.finalState}

INVARIANT CHECKS:
${JSON.stringify(sanitizedInvariants, null, 2)}

CHRONOLOGICAL EXECUTION TRACES:
${JSON.stringify(sanitizedTraces, null, 2)}

Provide your analysis in EXACTLY the following JSON structure:
{
  "rootCauseHypothesis": "string: concise, rigorous explanation of why this payment flow failed or succeeded",
  "evidence": ["string: specific factual observation 1 from traces", "observation 2", ...],
  "confidence": number between 80 and 99,
  "recommendedCodeFix": {
    "filename": "string: suggested file path",
    "explanation": "string: clear architectural and code-level explanation of the fix",
    "diff": "string: unified git diff syntax snippet showing exact before/after code changes"
  },
  "proposedRegressionTest": {
    "testName": "string: descriptive automated test function name",
    "description": "string: what the test verifies",
    "code": "string: executable TypeScript/Vitest test code"
  },
  "nextDiagnosticAction": "string: immediate next step the developer should take"
}

Do not invent errors if none exist. Stick strictly to observed evidence in the traces.
Respond with pure JSON only.`;

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    const text = response.text || '';
    // Clean markdown code blocks if present
    const cleanedText = text.replace(/```json\n?|\n?```/g, '').trim();
    const parsed = JSON.parse(cleanedText);

    return {
      rootCauseHypothesis: parsed.rootCauseHypothesis || 'Root cause identified from trace analysis.',
      evidence: Array.isArray(parsed.evidence) ? parsed.evidence : ['Trace analysis completed.'],
      confidence: typeof parsed.confidence === 'number' ? parsed.confidence : 95,
      modelName: 'Google Gemini 2.5 Flash',
      mode: 'LIVE_AI_MODEL',
      recommendedCodeFix: parsed.recommendedCodeFix || {
        filename: 'src/services/paypal.ts',
        explanation: 'Apply resilient error handling.',
        diff: '',
      },
      proposedRegressionTest: parsed.proposedRegressionTest || {
        testName: 'verify_payment_resilience',
        description: 'Automated resilience check',
        code: '',
      },
      nextDiagnosticAction: parsed.nextDiagnosticAction || 'Verify fix and rerun test.',
      disclaimer: 'Generated by Google Gemini 2.5 Flash on sanitized payment traces.',
    };
  } catch (err) {
    console.error('Error invoking Gemini AI diagnostic model, falling back to deterministic engine:', err);
    // Transparently fall back if API call fails (e.g. invalid key or network error)
    const fallback = generateDeterministicExpertDiagnosis(run);
    fallback.disclaimer = `Fallback to Deterministic Engine (Gemini API error: ${err instanceof Error ? err.message : String(err)})`;
    return fallback;
  }
}
